# Design Pattern Combinations
# ============================
# Real-world mini-applications showing how patterns
# synergize to solve complex problems together.
#
# Combinations:
#   1. Strategy + Factory       — Payment processing
#   2. Command + Memento        — Undo/redo text editor
#   3. Observer + Mediator      — Event-driven dashboard
#   4. Composite + Iterator     — File system browser
#   5. Decorator + Strategy     — API middleware pipeline
#   6. Builder + Composite      — HTML document builder
#   7. Factory + Observer + Strategy — Plugin system
#   8. MVC (Observer + Strategy + Composite) — Todo app
